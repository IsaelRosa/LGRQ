  UNIQUE KEY uq_solventes_codigo (codigo),
  KEY idx_solventes_validade (data_validade),
  KEY idx_solventes_status (status),
  KEY idx_solventes_laboratorio (laboratorio)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

