  embalagem VARCHAR(180) NULL,
  laboratorio VARCHAR(180) NULL,
  localizacao VARCHAR(255) NULL,
  data_recebimento DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  data_validade DATETIME(3) NULL,
  status VARCHAR(80) NOT NULL DEFAULT 'Em Estoque',
  inflamavel TINYINT(1) NOT NULL DEFAULT 0,
  responsavel VARCHAR(180) NULL,
  observacoes TEXT NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  atualizado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
