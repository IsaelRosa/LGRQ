CREATE TABLE IF NOT EXISTS notificacoes (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tipo VARCHAR(100) NOT NULL DEFAULT 'Aviso',
  severidade VARCHAR(30) NOT NULL DEFAULT 'info',
  titulo VARCHAR(255) NOT NULL,
  mensagem TEXT NULL,
  origem VARCHAR(80) NULL,
  origem_id VARCHAR(80) NULL,
  lida TINYINT(1) NOT NULL DEFAULT 0,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_notificacoes_lida_data (lida, criado_em),
  KEY idx_notificacoes_origem (origem, origem_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS historico (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tabela VARCHAR(80) NOT NULL,
  registro_id VARCHAR(80) NOT NULL,
  registro_codigo VARCHAR(100) NULL,
  acao VARCHAR(20) NOT NULL,
  descricao VARCHAR(500) NOT NULL,
  usuario VARCHAR(180) NOT NULL,
  usuario_email VARCHAR(255) NULL,
  dados_anteriores JSON NULL,
  dados_novos JSON NULL,
  mudancas JSON NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_historico_tabela_registro (tabela, registro_id),
  KEY idx_historico_data (criado_em),
  KEY idx_historico_usuario (usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

