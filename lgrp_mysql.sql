SET NAMES utf8mb4;
SET time_zone = '+00:00';
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome VARCHAR(180) NOT NULL,
  email VARCHAR(255) NOT NULL,
  papel VARCHAR(80) NOT NULL DEFAULT 'Técnico de Laboratório',
  setor VARCHAR(180) NULL,
  crq VARCHAR(80) NULL,
  telefone VARCHAR(40) NULL,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  auth_id VARCHAR(255) NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  atualizado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_usuarios_email (email),
  UNIQUE KEY uq_usuarios_auth_id (auth_id),
  KEY idx_usuarios_papel (papel),
  KEY idx_usuarios_setor (setor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS pedidos_coleta (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  codigo VARCHAR(40) NOT NULL,
  laboratorio VARCHAR(180) NOT NULL,
  solicitante VARCHAR(180) NOT NULL,
  usuario_id BIGINT UNSIGNED NULL,
  tipo_residuo VARCHAR(180) NOT NULL,
  grupo VARCHAR(100) NULL,
  classe VARCHAR(100) NULL,
  quantidade_estimada DECIMAL(14,3) NULL,
  unidade VARCHAR(20) NOT NULL DEFAULT 'kg',
  embalagem VARCHAR(180) NULL,
  local_coleta VARCHAR(255) NULL,
  data_solicitacao DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  data_prevista DATETIME(3) NULL,
  data_coleta DATETIME(3) NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'Solicitado',
  prioridade VARCHAR(30) NOT NULL DEFAULT 'Média',
  responsavel VARCHAR(180) NULL,
  risco VARCHAR(180) NULL,
  observacoes TEXT NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  atualizado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_pedidos_codigo (codigo),
  KEY idx_pedidos_usuario (usuario_id),
  KEY idx_pedidos_status (status),
  KEY idx_pedidos_data_solicitacao (data_solicitacao),
  CONSTRAINT fk_pedidos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coletas (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  pedido_id BIGINT UNSIGNED NULL,
  data_coleta DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  coletor VARCHAR(180) NULL,
  equipe VARCHAR(120) NULL,
  peso_kg DECIMAL(14,3) NULL,
  volume_l DECIMAL(14,3) NULL,
  unidades INT UNSIGNED NULL,
  destino_temporario VARCHAR(255) NULL,
  veiculo VARCHAR(180) NULL,
  mtr VARCHAR(80) NULL,
  observacoes TEXT NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_coletas_pedido (pedido_id),
  KEY idx_coletas_data (data_coleta),
  KEY idx_coletas_mtr (mtr),
  CONSTRAINT fk_coletas_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos_coleta (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tratamentos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  codigo VARCHAR(40) NOT NULL,
  pedido_id BIGINT UNSIGNED NULL,
  residuo VARCHAR(255) NOT NULL,
  grupo VARCHAR(100) NULL,
  metodo VARCHAR(180) NULL,
  quantidade_entrada DECIMAL(14,3) NULL,
  unidade VARCHAR(20) NOT NULL DEFAULT 'kg',
  quantidade_saida DECIMAL(14,3) NULL,
  eficiencia DECIMAL(7,3) NULL,
  data_inicio DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  data_conclusao DATETIME(3) NULL,
  operador VARCHAR(180) NULL,
  responsavel_tecnico VARCHAR(180) NULL,
  destino_final VARCHAR(255) NULL,
  cnpj_destinador VARCHAR(30) NULL,
  mtr VARCHAR(80) NULL,
  certificado VARCHAR(100) NULL,
  custo DECIMAL(14,2) NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'Agendado',
  observacoes TEXT NULL,
  criado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  atualizado_em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_tratamentos_codigo (codigo),
  KEY idx_tratamentos_pedido (pedido_id),
  KEY idx_tratamentos_status (status),
  KEY idx_tratamentos_data_inicio (data_inicio),
  CONSTRAINT fk_tratamentos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos_coleta (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS solventes (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  codigo VARCHAR(40) NOT NULL,
  nome VARCHAR(180) NOT NULL,
  formula VARCHAR(100) NULL,
  cas VARCHAR(40) NULL,
  categoria VARCHAR(100) NOT NULL DEFAULT 'Não Halogenado',
  pureza DECIMAL(7,3) NULL,
